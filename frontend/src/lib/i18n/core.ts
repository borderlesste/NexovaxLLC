import { en } from './en';
import { frDict } from './fr';
import { htDict } from './ht';

export type Locale = 'es' | 'en' | 'fr' | 'ht';
export const LOCALES: Locale[] = ['es', 'en', 'fr', 'ht'];
export const LOCALE_COOKIE = 'nx_locale';

export const isLocale = (v: unknown): v is Locale => v === 'es' || v === 'en' || v === 'fr' || v === 'ht';

/** Dictionaries tried in order (Spanish is the source and the last resort). */
const CHAIN: Record<Locale, Record<string, string>[]> = { es: [], en: [en], fr: [frDict, en], ht: [htDict, frDict, en] };

/** gettext-style lookup: the Spanish source text is the key; `{name}` placeholders are interpolated. */
/** Sentences generated by the API with embedded values. */
const PATTERNS: Record<Exclude<Locale, 'es'>, [RegExp, string][]> = {
  en: [
    [/^El vendedor despachó el paquete con (.+)\.$/, 'The seller shipped the package with $1.'],
    [/^(.+) despachó tu paquete con (.+)\.$/, '$1 shipped your package with $2.'],
    [/^Recoge tu pedido en la tienda del vendedor \((.+)\)$/, 'Pick up your order at the seller’s store ($1)'],
  ],
  fr: [
    [/^El vendedor despachó el paquete con (.+)\.$/, 'Le vendeur a expédié le colis avec $1.'],
    [/^(.+) despachó tu paquete con (.+)\.$/, '$1 a expédié votre colis avec $2.'],
    [/^Recoge tu pedido en la tienda del vendedor \((.+)\)$/, 'Retirez votre commande dans la boutique du vendeur ($1)'],
  ],
  ht: [
    [/^El vendedor despachó el paquete con (.+)\.$/, 'Machann nan voye koli a ak $1.'],
    [/^(.+) despachó tu paquete con (.+)\.$/, '$1 voye koli ou ak $2.'],
    [/^Recoge tu pedido en la tienda del vendedor \((.+)\)$/, 'Ranmase kòmand ou nan boutik machann nan ($1)'],
  ],
};

/** Whether the text has a real translation for this language (not a fallback). */
export function hasTranslation(locale: Locale, es: string) {
  if (locale === 'es') return true;
  return (locale === 'en' ? en : locale === 'fr' ? frDict : htDict)[es] !== undefined;
}

export function translate(locale: Locale, es: string, vars?: Record<string, string | number | null | undefined>) {
  let s = es;
  for (const d of CHAIN[locale]) {
    if (d[es] !== undefined) {
      s = d[es];
      break;
    }
  }
  if (locale !== 'es' && s === es) for (const [re, rep] of PATTERNS[locale]) if (re.test(es)) { s = es.replace(re, rep); break; }
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
  return s;
}

/** Number/date formatting. Haitian Creole has no Intl data: French formats (as used in Haiti) apply. */
export const intlLocale = (l: Locale) => ({ es: 'es-419', en: 'en-US', fr: 'fr-FR', ht: 'fr-HT' })[l];

/** Locale code for Stripe Elements and the PayPal SDK. */
export const stripeLocale = (l: Locale) => ({ es: 'es-419', en: 'en', fr: 'fr', ht: 'fr' })[l] as 'es-419' | 'en' | 'fr';
export const paypalLocale = (l: Locale) => ({ es: 'es_ES', en: 'en_US', fr: 'fr_FR', ht: 'fr_FR' })[l];
